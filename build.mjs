// build.mjs — one source of truth for the page and the gated kernel.
//
// Konomi Skins' fitting rules live in index.html (the live page), between the KERNEL:BEGIN and KERNEL:END markers. This
// script copies that block byte for byte into kernel.mjs, the module the tests and the witness mutation gate run
// against, so the page a person uses and the code the gate proves are the same code.
//
// It also writes the figures the page's explainer shows (the gate receipt and the sourced wage) into the page
// itself, between the SKINS-DATA markers, so the page reads them without a network call: it promises none.
//
//   node build.mjs           regenerate kernel.mjs and the page's data block
//   node build.mjs --check   exit 1 if either differs from what index.html and the source files produce (CI)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

export function extractKernel(html) {
  const b = html.match(/^.*KERNEL:BEGIN.*$/m);
  const e = html.match(/^.*KERNEL:END.*$/m);
  if (!b || !e || e.index < b.index) throw new Error('index.html: KERNEL:BEGIN / KERNEL:END markers missing or out of order');
  return html.slice(b.index + b[0].length + 1, e.index);
}

// Every top-level declaration in the block is exported, so nothing in the page is untestable.
// `var a = 1, b = [2, 3], c = f(4, 5);` declares a, b and c: split at commas outside brackets and strings.
function declaredNames(rest) {
  const names = [];
  let depth = 0, quote = null, part = '';
  for (const ch of rest + ',') {
    if (quote) { if (ch === quote) quote = null; part += ch; continue; }
    if (ch === '"' || ch === "'" || ch === '`') quote = ch;
    else if ('([{'.includes(ch)) depth++;
    else if (')]}'.includes(ch)) depth--;
    else if (ch === ';' && depth === 0) break;
    if (ch === ',' && depth === 0) {
      const m = part.match(/^\s*([A-Za-z_$][\w$]*)/);
      if (m) names.push(m[1]);
      part = '';
    } else part += ch;
  }
  const m = part.match(/^\s*([A-Za-z_$][\w$]*)/);
  if (m) names.push(m[1]);
  return names;
}

export function topLevelNames(code) {
  const names = [];
  for (const m of code.matchAll(/^(?:async\s+)?function\s+([A-Za-z_$][\w$]*)|^(?:var|let|const)\s+(.*)$/gm)) {
    if (m[1]) names.push(m[1]);
    else names.push(...declaredNames(m[2]));
  }
  return [...new Set(names)];
}

export function kernelModule(block) {
  return '// GENERATED by build.mjs from the KERNEL block in index.html: edit index.html, then run `node build.mjs`.\n' +
    block + 'export { ' + topLevelNames(block).join(', ') + ' };\n';
}


const DATA_BEGIN = '<!-- ⟦SKINS-DATA-BEGIN⟧ generated by build.mjs from receipts/witness.json and the vendored basis -->';
const DATA_END = '<!-- ⟦SKINS-DATA-END⟧ -->';
export function dataBlock() {
  const basis = JSON.parse(readFileSync('vendor/sovereign-enterprise/data/basis.json', 'utf8'));
  const data = {
    // null before the first gate run; gate.mjs --verify (CI) refuses a missing receipt
    receipt: existsSync('receipts/witness.json') ? JSON.parse(readFileSync('receipts/witness.json', 'utf8')) : null,
    basis: { wageMedianHourly: basis.wageMedianHourly },
  };
  // inside a script element, "</" could end it early: put a backslash between the two (JSON reads it back as "/")
  const BACKSLASH = String.fromCharCode(92), NEWLINE = String.fromCharCode(10);
  const json = JSON.stringify(data).split('</').join('<' + BACKSLASH + '/');
  return [DATA_BEGIN, '<script type="application/json" id="skins-data">' + json + '</script>', DATA_END].join(NEWLINE);
}
export function withData(html) {
  const i = html.indexOf(DATA_BEGIN), j = html.indexOf(DATA_END);
  if (i < 0 || j < i) throw new Error('index.html: SKINS-DATA markers missing or out of order');
  return html.slice(0, i) + dataBlock() + html.slice(j + DATA_END.length);
}

const html = readFileSync('index.html', 'utf8');
const want = kernelModule(extractKernel(html));
const page = withData(html);
if (process.argv.includes('--check')) {
  let have = '';
  try { have = readFileSync('kernel.mjs', 'utf8'); } catch {}
  if (have !== want) { console.error('✗ kernel.mjs differs from the KERNEL block in index.html: run node build.mjs'); process.exit(1); }
  if (page !== html) { console.error("✗ the page's data block is not the committed receipt and figures: run node build.mjs"); process.exit(1); }
  console.log('✓ kernel.mjs matches index.html, and the page carries the committed receipt and figures');
} else {
  writeFileSync('kernel.mjs', want);
  writeFileSync('index.html', page);
  console.log('wrote kernel.mjs (' + Buffer.byteLength(want) + " bytes) and the page's data block");
}
